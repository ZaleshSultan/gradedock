import {chromium} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.connectOverCDP(process.env.GRADEDOCK_CDP_URL,{noDefaults:true});
const page=browser.contexts()[0].pages()[0];
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const before=page.url();
await page.getByRole('button',{name:'Настройки',exact:true}).click();
await page.getByRole('button',{name:'Конфиденциальность',exact:true}).click();
await page.getByRole('button',{name:'Политика конфиденциальности',exact:true}).click();
await page.frameLocator('.document-frame').getByRole('heading',{name:'GradeDock Privacy Policy',exact:true}).waitFor();
if(page.url()!==before)throw new Error('Policy navigated away from the app');
await page.getByRole('button',{name:'Закрыть / Close'}).click();
await page.getByRole('button',{name:'Лицензии компонентов',exact:true}).click();
await page.frameLocator('.document-frame').getByText('MIT',{exact:false}).first().waitFor();
await page.getByRole('button',{name:'Закрыть / Close'}).click();
await page.getByRole('button',{name:'Предметы',exact:true}).click();
await page.locator('.forecast-value').waitFor();
const result={platform:await page.evaluate(()=>window.Capacitor.getPlatform()),policyInApp:true,licensesInApp:true,forecast:await page.locator('.forecast-value').textContent(),errors};
await writeFile('docs/native-document-qa.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result));await browser.close();
